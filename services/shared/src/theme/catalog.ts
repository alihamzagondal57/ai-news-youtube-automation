/**
 * The theme catalog: 18 distinct looks for the news composition.
 *
 * These are not palette swaps. Each theme picks a different combination of
 * *structural* variants — where the ticker sits and whether it's a solid band,
 * discrete chips, a thin ribbon or absent entirely; whether the headline plate is
 * a bar, a floating card, a rule-underline or a corner tag; which side it enters
 * from; how segments give way to each other — so two themes differ in composition
 * and rhythm, not only colour.
 *
 * Transition frame counts vary per theme (12–24). render-server keys its
 * targeted-re-render invalidation off this number, so it is load-bearing, not
 * decorative.
 */

