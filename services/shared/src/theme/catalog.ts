export const DEFAULT_THEME_ID = "midnight-wire";

const THEME_BY_ID = new Map(THEMES.map((theme) => [theme.id, theme]));

export function getTheme(themeId: string): Theme {
  const theme = THEME_BY_ID.get(themeId);
  if (!theme) {
    throw new Error(`Unknown theme id "${themeId}". Known ids: ${THEMES.map((t) => t.id).join(", ")}`);
  }
  return theme;
}

/** Non-throwing lookup for callers that want to fall back rather than fail a render. */
export function getThemeOrDefault(themeId: string | null | undefined): Theme {
  if (!themeId) return getTheme(DEFAULT_THEME_ID);
  return THEME_BY_ID.get(themeId) ?? getTheme(DEFAULT_THEME_ID);
}

export const THEME_IDS: readonly string[] = THEMES.map((theme) => theme.id);
